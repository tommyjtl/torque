"""Embed identical generated SPIR-V without parsing millions of C++ literals."""
import hashlib
import json
from pathlib import Path
import re

ARRAY = re.compile(r'^const unsigned char ([A-Za-z0-9_]+)_data\[(\d+)\] = \{\s*$')


def convert(source, target, receipt):
    shaders = source.parent / 'vulkan-shaders.spv'
    records = []
    with source.open() as original, target.open('w') as output:
        for line in original:
            match = ARRAY.fullmatch(line)
            if not match:
                output.write(line)
                continue
            name, length = match[1], int(match[2])
            digest = hashlib.sha256()
            size = 0
            for payload in original:
                if payload.strip() == '};':
                    break
                values = [token.strip() for token in payload.split(',') if token.strip()]
                if not all(re.fullmatch(r'0x[0-9a-fA-F]{1,2}', token) for token in values):
                    raise ValueError('Unexpected generated byte-array syntax')
                block = bytes(int(token, 16) for token in values)
                digest.update(block)
                size += len(block)
            else:
                raise ValueError('Unterminated byte array')
            path = shaders / (name + '.spv')
            if not path.is_file():
                raise ValueError('Missing original SPIR-V: ' + name)
            expected = path.read_bytes()
            actual_hash = digest.hexdigest()
            if size != length or len(expected) != length or hashlib.sha256(expected).hexdigest() != actual_hash:
                raise ValueError('SPIR-V byte identity check failed: ' + name)
            if any(c in str(path) for c in ('"', '\n', '\\')):
                raise ValueError('Unsupported assembly input path')
            output.write('asm(R"TORQUE_SPV(\n.pushsection .rodata\n.balign 4\n')
            output.write(f'.global {name}_data\n.type {name}_data, %object\n{name}_data:\n')
            output.write(f'.incbin "{path}"\n.size {name}_data, {length}\n')
            output.write('.popsection\n)TORQUE_SPV");\n')
            records.append({'name': name, 'bytes': length, 'sha256': actual_hash})
    if not records:
        raise ValueError('No shader arrays found')
    receipt.write_text(json.dumps({'source': str(source), 'source_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                                   'shader_arrays': records, 'byte_identity_verified': True}, indent=2))


if __name__ == '__main__':
    import sys
    convert(*map(Path, sys.argv[1:4]))
